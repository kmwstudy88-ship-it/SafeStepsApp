function buildScenes(story: StorySeed): StorybookScene[] {
  return [
    {
      id: story.uiFlow[0],
      screenId: `${story.scenePrefix}_intro`,
      type: "intro",
      title: "Opening",
      narration: story.setup,
      components: ["NarrationText", "SceneImage", "CharacterAvatar"],
      engineHooks: story.engineHooks.filter((hook) => hook === "emotion_engine"),
    },
    {
      id: story.uiFlow[1],
      screenId: `${story.scenePrefix}_scene`,
      type: story.uiFlow[1].toLowerCase().includes("emotion") ? "emotion-check" : "static-scene",
      title: "Story Moment",
      narration: story.problem,
      components: ["SceneImage", "PromptText"],
      choices: story.choices,
    },
    {
      id: story.uiFlow[2],
      screenId: `${story.scenePrefix}_activity`,
      type: "activity",
      title: "Child Interaction",
      narration: story.activity,
      components: ["ChoiceButtons", "InteractionController", "ProgressIndicator"],
      choices: story.choices,
      engineHooks: story.engineHooks,
    },
    {
      id: story.uiFlow[3],
      screenId: `${story.scenePrefix}_resolution`,
      type: "resolution",
      title: "Resolution",
      narration: story.resolution,
      components: ["NarrationText", "OutcomeState", "ProgressionUnlock"],
    },
    {
      id: story.uiFlow[story.uiFlow.length - 1],
      screenId: `${story.scenePrefix}_reflection`,
      type: "reflection",
      title: "Reflection",
      narration: story.childPrompts[0],
      components: ["ReflectionPrompt", "ParentPrompt", "ChildPrompt"],
      choices: story.childPrompts,
      engineHooks: story.engineHooks.filter((hook) => hook === "reflection_engine"),
    },
  ];
}

export const interactiveStorybooks: InteractiveStorybook[] = storySeeds.map((story) => ({
  ...story,
  scenes: buildScenes(story),
}));

