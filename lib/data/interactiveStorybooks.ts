export function getInteractiveStorybookById(id: string) {
  return interactiveStorybooks.find((story) => story.id === id);
}

export function getInteractiveStorybooksByAge(age: number) {
  return interactiveStorybooks.filter((story) => {
    const [min, max] = story.ageRange.split("-").map(Number);
    return age >= min && age <= max;
  });
}

export function getInteractiveStorybookCatalogueSummary() {
  const themes = new Set(interactiveStorybooks.map((story) => story.theme));
  const engineHooks = new Set(interactiveStorybooks.flatMap((story) => story.engineHooks));

  return {
    total: interactiveStorybooks.length,
    firstId: interactiveStorybooks[0]?.id,
    lastId: interactiveStorybooks[interactiveStorybooks.length - 1]?.id,
    themeCount: themes.size,
    engineHookCount: engineHooks.size,
    sceneCount: interactiveStorybooks.reduce((total, story) => total + story.scenes.length, 0),
  };
}
