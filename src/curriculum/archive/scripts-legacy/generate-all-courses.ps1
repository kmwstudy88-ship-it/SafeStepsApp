# --------------------------------------------
#  Generate Folders + JSON Files
# --------------------------------------------

foreach ($topic in $topics) {

    # Convert topic → safe folder name
    $safe = ($topic -replace '[^\w\- ]','').Replace(' ','-').ToLower()

    $coursePath = Join-Path $basePath $safe
    $filePath   = Join-Path $coursePath "course.json"

    if (-not (Test-Path $coursePath)) {
        New-Item -ItemType Directory -Path $coursePath -Force | Out-Null
        Write-Host "Created folder: $coursePath"
    }

    $courseObject = [PSCustomObject]@{
        title                = $topic
        description          = ""
        estimatedTimeMinutes = 60
        difficultyLevel      = "beginner"
        learningOutcomes     = @()
        modules              = @()
        metadata             = @{
            tags         = @()
            audience     = "parents"
            jurisdiction = "AU"
        }
    }

    $json = $courseObject | ConvertTo-Json -Depth 10
    $json | Set-Content -Path $filePath -Encoding UTF8

    Write-Host "Created: $safe\course.json"
}
